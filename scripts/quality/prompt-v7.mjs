function gradeNum(grade){
  const gn=(String(grade).match(/([0-9１-９一二三四五六])/)||[])[1];
  const map={'一':1,'二':2,'三':3,'四':4,'五':5,'六':6};
  return map[gn]!==undefined?map[gn]:(parseInt(String(gn||'').replace(/[１-９]/g,c=>String.fromCharCode(c.charCodeAt(0)-0xFEE0)),10)||0);
}

